package report

import (
	"fmt"
	"io"
	"regexp"
	"strings"

	"github.com/Ri4dH/failtrace/internal/joblog"
	"github.com/Ri4dH/failtrace/internal/plan"
	"github.com/Ri4dH/failtrace/internal/repro"
)

var verdictMarkdown = map[repro.Verdict]string{
	repro.VerdictReproduced:    "✅ Reproduced",
	repro.VerdictDifferent:     "⚠️ Different failure",
	repro.VerdictNotReproduced: "❌ Not reproduced",
	repro.VerdictDiverged:      "⚠️ Diverged",
	repro.VerdictFlaky:         "🎲 Flaky",
}

var verdictSentence = map[repro.Verdict]string{
	repro.VerdictReproduced:    "fails locally the same way it failed in CI",
	repro.VerdictDifferent:     "fails locally, but not the way it failed in CI",
	repro.VerdictNotReproduced: "passed locally",
	repro.VerdictDiverged:      "never ran locally, because an earlier step failed",
	repro.VerdictFlaky:         "fails only some of the time",
}

// WriteMarkdown renders a reproduction as a Markdown report for issues and
// pull requests.
func WriteMarkdown(w io.Writer, p *plan.Plan, res *repro.Result) error {
	var b strings.Builder
	target := targetStep(p)

	fmt.Fprintf(&b, "## FailTrace: %s\n\n", verdictMarkdown[res.Verdict])
	job := mdCode(p.Job.Name)
	if p.Job.URL != "" {
		job = fmt.Sprintf("[%s](%s)", job, p.Job.URL)
	}
	link := ""
	if p.RunURL != "" {
		link = fmt.Sprintf(" ([CI run](%s))", p.RunURL)
	}
	fmt.Fprintf(&b, "The step **%s** of job %s in `%s` %s%s.\n\n",
		mdText(target), job, p.Repository, verdictSentence[res.Verdict], link)
	for _, r := range res.Reasons {
		fmt.Fprintf(&b, "- %s\n", mdText(r))
	}

	b.WriteString("\n|  | CI | Local |\n|---|---|---|\n")
	mdRow(&b, "Exit code", exitText(res.CI), localExit(res))
	mdRow(&b, "Failure", categoryText(res.CI), categoryText(res.Local))
	if hasTests(res.CI) || hasTests(res.Local) {
		mdRow(&b, "Failed tests", testsText(res.CI), testsText(res.Local))
	}
	if len(res.Attempts) > 1 {
		failed := 0
		for _, a := range res.Attempts {
			if a.ExitCode != 0 {
				failed++
			}
		}
		mdRow(&b, "Runs", "failed 1 of 1", fmt.Sprintf("failed %d of %d", failed, len(res.Attempts)))
	}

	b.WriteString("\n### Environment\n\n")
	img := "`" + p.Image.Ref + "`"
	if p.Image.Exact {
		img += " (the job's container)"
	}
	fmt.Fprintf(&b, "- **Image:** %s on `%s` (CI: `%s`)\n", img, res.Platform, p.Image.Platform)
	fmt.Fprintf(&b, "- **Commit:** `%s`%s\n", short(p.Commit), mergeNote(p))
	if len(p.Toolchains) > 0 {
		var tcs []string
		for _, t := range p.Toolchains {
			tcs = append(tcs, fmt.Sprintf("%s `%s`", t.Tool, orDash(t.Version)))
		}
		fmt.Fprintf(&b, "- **Toolchains:** %s\n", strings.Join(tcs, ", "))
	}
	if len(p.Services) > 0 {
		var svcs []string
		for _, s := range p.Services {
			svcs = append(svcs, fmt.Sprintf("%s (`%s`)", s.Name, s.Image))
		}
		fmt.Fprintf(&b, "- **Services:** %s\n", strings.Join(svcs, ", "))
	}

	if len(res.Differences) > 0 {
		b.WriteString("\n### Differences from CI\n\n")
		for _, d := range res.Differences {
			fmt.Fprintf(&b, "- %s\n", mdText(shortenRefs(d)))
		}
	}

	b.WriteString("\n### Steps\n\n| # | Step | Result | Time |\n|---|---|---|---|\n")
	for _, s := range res.Steps {
		result := string(s.Status)
		if s.ExitCode != nil {
			result += fmt.Sprintf(" (exit %d)", *s.ExitCode)
		}
		if s.Note != "" && s.Status == repro.StepSkipped {
			result += ": " + s.Note
		}
		name := mdCell(shortenRefs(s.Name))
		if s.Target {
			name = "**" + name + "** ← failed in CI"
		}
		secs := ""
		if s.Seconds > 0 {
			secs = fmt.Sprintf("%.1fs", s.Seconds)
		}
		fmt.Fprintf(&b, "| %d | %s | %s | %s |\n", s.Index, name, mdCell(result), secs)
	}

	for _, s := range res.Steps {
		if len(s.Output) == 0 {
			continue
		}
		label := "Local output of the failing step"
		if !s.Target {
			label = fmt.Sprintf("Local output of step %d, which failed", s.Index)
		}
		fence := codeFence(s.Output)
		fmt.Fprintf(&b, "\n<details><summary>%s (last %d lines)</summary>\n\n%stext\n%s\n%s\n\n</details>\n",
			label, len(s.Output), fence, strings.Join(s.Output, "\n"), fence)
	}
	if ci := res.CI; ci != nil && len(ci.Excerpt) > 0 {
		fence := codeFence(ci.Excerpt)
		fmt.Fprintf(&b, "\n<details><summary>CI output of the failing step (excerpt)</summary>\n\n%stext\n%s\n%s\n\n</details>\n",
			fence, strings.Join(ci.Excerpt, "\n"), fence)
	}

	fmt.Fprintf(&b, "\n<sub>Generated by [FailTrace](https://github.com/Ri4dH/failtrace) in %.0fs.", res.Seconds)
	if p.RunURL != "" {
		fmt.Fprintf(&b, " Reproduce it yourself: `failtrace repro %s`", p.RunURL)
	}
	b.WriteString("</sub>\n")
	_, err := io.WriteString(w, b.String())
	return err
}

func targetStep(p *plan.Plan) string {
	for _, s := range p.Steps {
		if s.Target {
			return s.Name
		}
	}
	return "that failed"
}

func mergeNote(p *plan.Plan) string {
	for _, s := range p.Steps {
		if co := s.Checkout; co != nil && co.MergeHead != "" {
			return fmt.Sprintf(", the merge of PR head `%s` into `%s` that CI tested", short(co.MergeHead), short(co.MergeBase))
		}
	}
	return ""
}

func mdRow(b *strings.Builder, label, ci, local string) {
	fmt.Fprintf(b, "| %s | %s | %s |\n", label, mdCell(orDash(ci)), mdCell(orDash(local)))
}

func exitText(f *joblog.Failure) string {
	if f == nil || f.ExitCode == nil {
		return ""
	}
	return fmt.Sprint(*f.ExitCode)
}

func localExit(res *repro.Result) string {
	if res.LocalExitCode == nil {
		return ""
	}
	return fmt.Sprint(*res.LocalExitCode)
}

func categoryText(f *joblog.Failure) string {
	if f == nil {
		return ""
	}
	return categoryLabels[f.Category]
}

func hasTests(f *joblog.Failure) bool { return f != nil && len(f.FailedTests) > 0 }

func testsText(f *joblog.Failure) string {
	if !hasTests(f) {
		return ""
	}
	const max = 10
	tests := f.FailedTests
	more := ""
	if len(tests) > max {
		more = fmt.Sprintf(" and %d more", len(tests)-max)
		tests = tests[:max]
	}
	quoted := make([]string, len(tests))
	for i, t := range tests {
		quoted[i] = mdCode(t)
	}
	return strings.Join(quoted, ", ") + more
}

var mdSpecialRe = regexp.MustCompile("([\\\\`*_{}\\[\\]<>#|])")

// mdText escapes Markdown syntax in prose, keeping backtick-quoted spans as code.
func mdText(s string) string {
	parts := strings.Split(s, "`")
	for i := range parts {
		if i%2 == 0 {
			parts[i] = mdSpecialRe.ReplaceAllString(parts[i], `\$1`)
		}
	}
	if len(parts)%2 == 0 { // unbalanced backtick: escape everything
		return mdSpecialRe.ReplaceAllString(s, `\$1`)
	}
	return strings.Join(parts, "`")
}

// mdCell makes text safe inside a table cell.
func mdCell(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "\n", " "), "|", `\|`)
}

// mdCode renders s as inline code, using a longer delimiter if s has backticks.
func mdCode(s string) string {
	delim := "`"
	for strings.Contains(s, delim) {
		delim += "`"
	}
	pad := ""
	if strings.HasPrefix(s, "`") || strings.HasSuffix(s, "`") {
		pad = " "
	}
	return delim + pad + s + pad + delim
}

// codeFence returns a fence longer than any backtick run in lines.
func codeFence(lines []string) string {
	fence := "```"
	for _, l := range lines {
		for strings.Contains(l, fence) {
			fence += "`"
		}
	}
	return fence
}
